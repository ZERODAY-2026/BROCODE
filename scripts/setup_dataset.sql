-- 1. Create Dedicated Role with Least Privilege
USE ROLE ACCOUNTADMIN;
CREATE ROLE IF NOT EXISTS DATAMIND_ROLE;
GRANT ROLE DATAMIND_ROLE TO ROLE SYSADMIN;

-- 2. Create Database & Schema
CREATE DATABASE IF NOT EXISTS DATAMIND_DB;
CREATE SCHEMA IF NOT EXISTS DATAMIND_DB.PUBLIC;

-- 3. Create Compute Warehouse
CREATE WAREHOUSE IF NOT EXISTS COMPUTE_WH
  WITH WAREHOUSE_SIZE = 'XSMALL'
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE;

-- 4. Grant Usage Permissions to Role
GRANT USAGE ON WAREHOUSE COMPUTE_WH TO ROLE DATAMIND_ROLE;
GRANT USAGE ON DATABASE DATAMIND_DB TO ROLE DATAMIND_ROLE;
GRANT USAGE ON SCHEMA DATAMIND_DB.PUBLIC TO ROLE DATAMIND_ROLE;

-- 5. Create Sample Analytics Table: WORLD_INDICATORS
USE DATABASE DATAMIND_DB;
USE SCHEMA PUBLIC;

CREATE OR REPLACE TABLE WORLD_INDICATORS (
    COUNTRY VARCHAR(100) NOT NULL,
    COUNTRY_CODE VARCHAR(3) NOT NULL,
    CONTINENT VARCHAR(50) NOT NULL,
    YEAR INT NOT NULL,
    GDP_USD NUMBER(18, 2),
    POPULATION NUMBER(14, 0),
    LIFE_EXPECTANCY NUMBER(5, 2),
    CO2_EMISSIONS_PER_CAPITA NUMBER(6, 2),
    INTERNET_USERS_PCT NUMBER(5, 2),
    PRIMARY KEY (COUNTRY_CODE, YEAR)
);

-- 6. Grant Read-Only (SELECT) Privileges (Least Privilege Security Guarantee)
GRANT SELECT ON TABLE DATAMIND_DB.PUBLIC.WORLD_INDICATORS TO ROLE DATAMIND_ROLE;
GRANT SELECT ON ALL TABLES IN SCHEMA DATAMIND_DB.PUBLIC TO ROLE DATAMIND_ROLE;

